class Command(BaseCommand):
    help = "Estimate price_per_kg for ingredients that are missing it"

    def add_arguments(self, parser):
        parser.add_argument(
            "--dry-run",
            action="store_true",
            help="Show what would be updated without saving",
        )

    def handle(self, *args, **options):
        dry_run = options["dry_run"]
        missing = Ingredient.objects.filter(price_per_kg__isnull=True)
        self.stdout.write(f"Ingredients without price: {missing.count()}")

        updated = 0
        not_found = []
        for ingredient in missing:
            if ingredient.name in PRICE_ESTIMATES:
                if not dry_run:
                    ingredient.price_per_kg = Decimal(str(PRICE_ESTIMATES[ingredient.name]))
                    ingredient.save(update_fields=["price_per_kg"])
                updated += 1
            else:
                not_found.append(ingredient.name)

        prefix = "[DRY RUN] " if dry_run else ""
        self.stdout.write(self.style.SUCCESS(f"{prefix}Updated: {updated}"))
        self.stdout.write(f"Not matched: {len(not_found)}")
        for name in sorted(not_found):
            self.stdout.write(f"  - {name}")
